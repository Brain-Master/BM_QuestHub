#!/usr/bin/env node
/**
 * Timeweb Cloud API — list/create S3 buckets and write scripts/s3.env.
 *
 *   node scripts/timeweb-provision-s3.mjs
 *   node scripts/timeweb-provision-s3.mjs --create bm-questhub
 *   node scripts/timeweb-provision-s3.mjs --setup bm-questhub
 *
 * Requires TIMEWEB_API_TOKEN in scripts/timeweb.env or env (Cloud API JWT).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadRepoEnv } from "./load-dotenv.mjs";

const ROOT = loadRepoEnv();
const API = "https://api.timeweb.cloud";
const S3_ENV = path.join(ROOT, "scripts", "s3.env");

async function api(pathname, options = {}) {
  const token = process.env.TIMEWEB_API_TOKEN?.trim();
  if (!token) {
    console.error(
      "[timeweb-provision] Missing TIMEWEB_API_TOKEN — copy scripts/timeweb.env.example to scripts/timeweb.env",
    );
    process.exit(1);
  }
  const res = await fetch(`${API}${pathname}`, {
    ...options,
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
      ...(options.headers || {}),
    },
  });
  const text = await res.text();
  let body;
  try {
    body = text ? JSON.parse(text) : null;
  } catch {
    body = text;
  }
  if (!res.ok) {
    console.error(`[timeweb-provision] ${res.status} ${pathname}`, body);
    process.exit(1);
  }
  return body;
}

function bucketList(body) {
  return body?.buckets ?? body?.storages ?? body?.storage ?? [];
}

function pickPresetId(presets) {
  const list =
    presets?.storages_presets ??
    presets?.storage_presets ??
    presets?.presets ??
    [];
  const oneGb = list.find((p) => p.size === 1 || p.disk === 1 || p.name?.includes("1"));
  return (oneGb ?? list[0])?.id;
}

function writeS3Env(bucket) {
  const name = bucket.name;
  const accessKey = bucket.access_key ?? bucket.accessKey;
  const secretKey = bucket.secret_key ?? bucket.secretKey;
  if (!name || !accessKey || !secretKey) {
    console.error("[timeweb-provision] bucket response missing name/access_key/secret_key");
    process.exit(1);
  }
  const publicBase = `https://${name}.s3.twcstorage.ru`;
  const content = `# Generated by timeweb-provision-s3.mjs — do not commit
S3_BUCKET=${name}
S3_ENDPOINT=https://s3.twcstorage.ru
AWS_DEFAULT_REGION=ru-1
AWS_ACCESS_KEY_ID=${accessKey}
AWS_SECRET_ACCESS_KEY=${secretKey}

# NEXT_PUBLIC_S3_PUBLIC_BASE_URL=${publicBase}
`;
  fs.writeFileSync(S3_ENV, content, "utf8");
  console.log(`[timeweb-provision] wrote ${path.relative(ROOT, S3_ENV)}`);
  console.log(`[timeweb-provision] public base: ${publicBase}`);
}

async function findBucket(name) {
  const body = await api("/api/v1/storages/buckets");
  return bucketList(body).find((b) => b.name === name);
}

async function createBucket(name) {
  const presets = await api("/api/v1/presets/storages");
  const presetId = pickPresetId(presets);
  if (!presetId) {
    console.error("[timeweb-provision] no storage preset id in API response");
    process.exit(1);
  }
  console.log(`[timeweb-provision] creating "${name}" (preset ${presetId}, type public)...`);
  const created = await api("/api/v1/storages/buckets", {
    method: "POST",
    body: JSON.stringify({
      name,
      type: "public",
      preset_id: presetId,
    }),
  });
  return created?.bucket ?? created;
}

async function main() {
  const setup = process.argv.includes("--setup");
  const createFlag = process.argv.includes("--create");
  const nameArg =
    process.argv.find((a, i) => process.argv[i - 1] === "--create") ??
    process.argv.find((a, i) => process.argv[i - 1] === "--setup") ??
    "bm-quest-s3-hot";

  if (!createFlag && !setup) {
    console.log("[timeweb-provision] storage presets:");
    console.log(JSON.stringify(await api("/api/v1/presets/storages"), null, 2));
    console.log("\n[timeweb-provision] buckets:");
    console.log(JSON.stringify(await api("/api/v1/storages/buckets"), null, 2));
    return;
  }

  let bucket = await findBucket(nameArg);
  if (!bucket) {
    bucket = await createBucket(nameArg);
  } else {
    console.log(`[timeweb-provision] bucket "${nameArg}" already exists (id ${bucket.id})`);
    if (!bucket.access_key && !bucket.accessKey) {
      const detail = await api(`/api/v1/storages/buckets/${bucket.id}`);
      bucket = detail?.bucket ?? detail;
    }
  }

  if (setup) {
    writeS3Env(bucket);
    console.log(
      "\n[timeweb-provision] Public bucket may not need extra policy.",
      "If objects are not readable, apply scripts/timeweb-s3-bucket-policy.example.json in the panel.",
    );
    console.log("Next: make s3-sync-data");
  } else {
    console.log(JSON.stringify(bucket, null, 2));
    console.log("\nRun with --setup to write scripts/s3.env from API keys.");
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
