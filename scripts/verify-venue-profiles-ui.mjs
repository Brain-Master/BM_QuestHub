import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../apps/web/package.json',import.meta.url));
const {chromium,expect}=require('@playwright/test');
const base=process.env.PREVIEW_URL||'http://127.0.0.1:3199';
if(!/^http:\/\/127\.0\.0\.1:\d+$/.test(base))throw Error('LOCAL_ONLY');
const browser=await chromium.launch({headless:true,executablePath:'/home/xipsin/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome'});
const checks=[],writes=[];
try{
 const c=await browser.newContext({viewport:{width:390,height:900}});
 await c.route('**/*',r=>{if(!['GET','HEAD'].includes(r.request().method())){writes.push(r.request().method());return r.abort();}return r.request().url().startsWith(base+'/')?r.continue():r.abort();});
 const p=await c.newPage();
 const go=async path=>{await p.goto(base+path,{waitUntil:'networkidle'});const consent=p.getByRole('button',{name:'Только необходимое'});if(await consent.isVisible())await consent.click();};
 await go('/sites/school-937/');
 await expect(p.locator('#venue-addresses [data-campus]')).toHaveCount(2);
 await expect(p.locator('#venue-addresses [data-campus]').first()).toHaveAttribute('data-campus','school-937-marshala-zakharova-25');
 await expect(p.locator('main')).toContainText('кабинет 103');
 await expect(p.locator('main')).toContainText('Локтеева Ирина Дмитриевна');
 await expect(p.getByTestId('finder-count')).toHaveText('4');
 const map=new URL(await p.locator('main iframe').getAttribute('src'));
 assert.ok(map.searchParams.getAll('pt').some(pt=>pt.startsWith('37.699562,55.61904,')));
 assert.ok(map.searchParams.getAll('pt').some(pt=>pt.startsWith('37.701485,55.619313,')));
 await expect(p.locator('#venue-photos img')).toHaveCount(2);
 await expect(p.locator('#venue-photos img').first()).toHaveAttribute('src','/sites/school-937/zakharova-25-original.jpg');
 checks.push('937 exact two buildings/map points;25 shown first; no fabricated groups; conflict explicit');
 await go('/sites/school-37/');
 await expect(p.getByRole('img',{name:'Здание школы № 37 на Мичуринском проспекте, 28',exact:true})).toBeVisible();
 await expect(p.getByTestId('finder-count')).toHaveText('9');
 await p.getByRole('navigation',{name:'Разделы площадки'}).getByRole('link',{name:'Фотографии',exact:true}).click();
 await expect(p).toHaveURL(/#venue-photos$/);
 await expect(p.locator('#venue-photos img')).toHaveAttribute('src','/sites/school-37/michurinsky-28-original.jpg');
 await expect(p.getByRole('link',{name:'Источник фото: Яндекс Карты ↗'})).toHaveAttribute('href',/1318471492/);
 await expect(p.locator('main')).not.toContainText('Открытые группы');
 await p.getByRole('navigation',{name:'Разделы площадки'}).getByRole('link',{name:'Связаться',exact:true}).click();
 await expect(p).toHaveURL(/#venue-contact$/);
 await expect(p.locator('#venue-contact').getByRole('link',{name:/Позвонить:/})).toHaveAttribute('href',/^tel:/);
 await p.getByRole('link',{name:'Расписание этого корпуса →'}).click();
 await expect(p).toHaveURL(/venue=school-37-michurinsky-28/);
 await expect(p.getByTestId('finder-count')).toHaveText('9');
 await p.locator('[data-annual-group] summary').first().click();
 await expect(p.locator('[data-annual-group]').first()).toContainText('Преподаватель подтверждён командой BrainMaster');
 checks.push('37 actual image/source, navigation anchors, phone, exact-campus schedule and owner teacher attribution');
 await go('/sites/37/');
 const canonical=await p.locator('link[rel="canonical"]').getAttribute('href');
 assert.equal(new URL(canonical).pathname,'/sites/school-37/');
 await go('/sites/bm-base-moscow/');
 await expect(p.getByRole('heading',{name:'О будущем открытии'})).toBeVisible();
 await expect(p.locator('#venue-contact')).toContainText('посещение и запись на занятия пока не предусмотрены');
 checks.push('numeric alias canonical; preparation-specific contact; no enrollment submissions');
 assert.deepEqual(writes,[]);
 await fs.mkdir('/tmp/questhub-venue-after',{recursive:true});
 await fs.writeFile('/tmp/questhub-venue-after/journey.json',JSON.stringify({checkedAt:new Date().toISOString(),base,checks,writes},null,2)+'\n');
 console.log(JSON.stringify({checks,writes}));
}finally{await browser.close();}
