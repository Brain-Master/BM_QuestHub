#!/usr/bin/env node
/**
 * Write scripts/s3-hot.env and scripts/s3.env from secret/bm-questhub-s3-hot.txt (gitignored outputs).
 *
 *   node scripts/setup-s3-hot-env.mjs
 *   node scripts/setup-s3-hot-env.mjs --write-web-env
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { loadRepoEnv } from "./load-dotenv.mjs";
import { parseTimewebS3SecretFile } from "./lib/parse-timeweb-s3-secret.mjs";
import {
  S3_STORAGE_DEFAULTS,
  S3_TIMEWEB_ENDPOINT,
  S3_TIMEWEB_REGION,
  S3_TIMEWEB_YCF_PACKAGE_BUCKET,
  publicBaseUrlFromEndpoint,
} from "./lib/s3-storage.mjs";

const ROOT = loadRepoEnv();
const SECRET = path.join(ROOT, "secret", "bm-questhub-s3-hot.txt");
const HOT_ENV = path.join(ROOT, "scripts", "s3-hot.env");
const ACTIVE_ENV = path.join(ROOT, "scripts", "s3.env");
const WEB_LOCAL = path.join(ROOT, "apps", "web", ".env.local");

function main() {
  const creds = parseTimewebS3SecretFile(SECRET);
  const bucket = creds.bucket || S3_STORAGE_DEFAULTS.legacy.bucket;
  const publicBase = publicBaseUrlFromEndpoint(S3_TIMEWEB_ENDPOINT, bucket);

  const body = `# Generated by setup-s3-hot-env.mjs — Timeweb rollback (do not commit)
S3_STORAGE_PROFILE=legacy
S3_BUCKET=${bucket}
S3_LEGACY_BUCKET=${bucket}
S3_LEGACY_ENDPOINT=${S3_TIMEWEB_ENDPOINT}
S3_LEGACY_PUBLIC_BASE_URL=${publicBase}
YCF_PACKAGE_BUCKET=${S3_TIMEWEB_YCF_PACKAGE_BUCKET}
S3_PUBLIC_BASE_URL=${publicBase}
S3_ENDPOINT=${S3_TIMEWEB_ENDPOINT}
AWS_DEFAULT_REGION=${S3_TIMEWEB_REGION}
AWS_ACCESS_KEY_ID=${creds.accessKeyId}
AWS_SECRET_ACCESS_KEY=${creds.secretAccessKey}
`;

  fs.writeFileSync(HOT_ENV, body, "utf8");
  console.log(`[setup-s3-hot] wrote ${path.relative(ROOT, HOT_ENV)} (Timeweb rollback snapshot)`);
  console.log(`[setup-s3-hot] active profile: run setup-s3-yc-env or set S3_STORAGE_PROFILE=legacy in scripts/s3.env`);
  console.log(`[setup-s3-hot] bucket=${bucket} public=${publicBase}`);

  if (process.argv.includes("--write-web-env")) {
    const prev = fs.existsSync(WEB_LOCAL) ? fs.readFileSync(WEB_LOCAL, "utf8") : "";
    const lines = new Map();
    for (const line of prev.split(/\r?\n/)) {
      const t = line.trim();
      if (!t || t.startsWith("#")) continue;
      const eq = t.indexOf("=");
      if (eq > 0) lines.set(t.slice(0, eq), t.slice(eq + 1));
    }
    lines.set("NEXT_PUBLIC_S3_PUBLIC_BASE_URL", publicBase);
    lines.set("SITE_SNAPSHOT_SOURCE", "s3");
    lines.set("S3_STORAGE_PROFILE", "hot");
    const out = [
      "# Hot S3 — generated by setup-s3-hot-env.mjs",
      ...[...lines.entries()].map(([k, v]) => `${k}=${v}`),
      "",
    ].join("\n");
    fs.writeFileSync(WEB_LOCAL, out, "utf8");
    console.log(`[setup-s3-hot] wrote ${path.relative(ROOT, WEB_LOCAL)}`);
  }
}

main();
