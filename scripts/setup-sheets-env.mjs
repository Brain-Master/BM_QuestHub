#!/usr/bin/env node
/**
 * Build scripts/sheets.env from secret/bm-questhub-*.json (gitignored).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SECRET_DIR = path.join(ROOT, "secret");
const OUT = path.join(ROOT, "scripts", "sheets.env");

function findKeyFile() {
  if (!fs.existsSync(SECRET_DIR)) {
    throw new Error(`Missing ${SECRET_DIR}`);
  }
  const files = fs
    .readdirSync(SECRET_DIR)
    .filter((n) => n.endsWith(".json") && n.includes("bm-questhub"));
  if (files.length === 0) {
    throw new Error("No bm-questhub*.json in secret/");
  }
  return path.join(SECRET_DIR, files[0]);
}

const keyPath = findKeyFile();
const jsonOneLine = JSON.stringify(JSON.parse(fs.readFileSync(keyPath, "utf8")));

const lines = [
  "# Generated by scripts/setup-sheets-env.mjs — do not commit",
  "GOOGLE_SHEETS_HOT_SPREADSHEET_ID=1ut5AhfJqx9wrJE3tTCzrkrQdCmWsCPB8cueHH3QsLy8",
  "GOOGLE_SHEETS_HOT_RANGE_GROUPS='Группы'!A:AZ",
  "GOOGLE_SHEETS_HOT_RANGE_FORMATS='Форматы'!A:AZ",
  "GOOGLE_SHEETS_COLD_SPREADSHEET_ID=1fqeVC8BhjGWtOR20NhCUQuhwgchkCCzYsmiudpGE4jc",
  "GOOGLE_SHEETS_COLD_RANGE_WORLDS='Миры'!A:Z",
  "GOOGLE_SHEETS_COLD_RANGE_VENUES='Площадки'!A:Z",
  "GOOGLE_SHEETS_COLD_RANGE_COURSES='Курсы'!A:Z",
  `GOOGLE_SERVICE_ACCOUNT_JSON=${jsonOneLine}`,
  "",
];

fs.writeFileSync(OUT, lines.join("\n"), "utf8");
const email = JSON.parse(jsonOneLine).client_email;
console.log(`[setup-sheets-env] wrote ${path.relative(ROOT, OUT)}`);
console.log(`[setup-sheets-env] service account: ${email}`);
