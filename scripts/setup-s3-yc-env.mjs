#!/usr/bin/env node
/**
 * Write scripts/s3-yc.env and scripts/s3.env from secret/bm-questhub-s3-yc.txt (gitignored outputs).
 *
 *   node scripts/setup-s3-yc-env.mjs
 *   node scripts/setup-s3-yc-env.mjs --write-web-env
 */
import fs from "node:fs";
import path from "node:path";

import { loadRepoEnv } from "./load-dotenv.mjs";
import { parseTimewebS3SecretFile } from "./lib/parse-timeweb-s3-secret.mjs";
import {
  S3_STORAGE_DEFAULTS,
  S3_TIMEWEB_ENDPOINT,
  S3_YC_ENDPOINT,
  S3_YC_REGION,
  publicBaseUrlFromEndpoint,
} from "./lib/s3-storage.mjs";

const ROOT = loadRepoEnv();
const SECRET_CANDIDATES = [
  path.join(ROOT, "secret", "bm-questhub-s3-yc.txt"),
  path.join(ROOT, "secret", "bm-questhub-s3.txt"),
];
const YC_ENV = path.join(ROOT, "scripts", "s3-yc.env");
const ACTIVE_ENV = path.join(ROOT, "scripts", "s3.env");
const WEB_LOCAL = path.join(ROOT, "apps", "web", ".env.local");

function resolveSecretPath() {
  for (const p of SECRET_CANDIDATES) {
    if (fs.existsSync(p)) return p;
  }
  throw new Error(
    `missing YC S3 secret — create one of:\n  ${SECRET_CANDIDATES.join("\n  ")}`,
  );
}

function main() {
  const secretPath = resolveSecretPath();
  const creds = parseTimewebS3SecretFile(secretPath);
  const bucket = creds.bucket || S3_STORAGE_DEFAULTS.hot.bucket;
  const legacyBucket = S3_STORAGE_DEFAULTS.legacy.bucket;
  const publicBase = publicBaseUrlFromEndpoint(S3_YC_ENDPOINT, bucket);
  const legacyPublic = publicBaseUrlFromEndpoint(S3_TIMEWEB_ENDPOINT, legacyBucket);

  const body = `# Generated by setup-s3-yc-env.mjs — do not commit
S3_STORAGE_PROFILE=hot
S3_BUCKET=${bucket}
S3_LEGACY_BUCKET=${legacyBucket}
S3_LEGACY_ENDPOINT=${S3_TIMEWEB_ENDPOINT}
S3_LEGACY_PUBLIC_BASE_URL=${legacyPublic}
YCF_PACKAGE_BUCKET=${bucket}
S3_PUBLIC_BASE_URL=${publicBase}
S3_ENDPOINT=${S3_YC_ENDPOINT}
AWS_DEFAULT_REGION=${S3_YC_REGION}
AWS_ACCESS_KEY_ID=${creds.accessKeyId}
AWS_SECRET_ACCESS_KEY=${creds.secretAccessKey}
`;

  fs.writeFileSync(YC_ENV, body, "utf8");
  fs.writeFileSync(ACTIVE_ENV, body, "utf8");
  console.log(`[setup-s3-yc] wrote ${path.relative(ROOT, YC_ENV)}`);
  console.log(`[setup-s3-yc] wrote ${path.relative(ROOT, ACTIVE_ENV)} (active)`);
  console.log(`[setup-s3-yc] bucket=${bucket} public=${publicBase}`);

  if (process.argv.includes("--write-web-env")) {
    const prev = fs.existsSync(WEB_LOCAL) ? fs.readFileSync(WEB_LOCAL, "utf8") : "";
    const lines = new Map();
    for (const line of prev.split(/\r?\n/)) {
      const t = line.trim();
      if (!t || t.startsWith("#")) continue;
      const eq = t.indexOf("=");
      if (eq > 0) lines.set(t.slice(0, eq), t.slice(eq + 1));
    }
    lines.set("NEXT_PUBLIC_S3_PUBLIC_BASE_URL", publicBase);
    lines.set("SITE_SNAPSHOT_SOURCE", "s3");
    lines.set("S3_STORAGE_PROFILE", "hot");
    const out = [
      "# YC Object Storage — generated by setup-s3-yc-env.mjs",
      ...[...lines.entries()].map(([k, v]) => `${k}=${v}`),
      "",
    ].join("\n");
    fs.writeFileSync(WEB_LOCAL, out, "utf8");
    console.log(`[setup-s3-yc] wrote ${path.relative(ROOT, WEB_LOCAL)}`);
  }
}

main();
